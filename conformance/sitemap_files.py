"""TS15 native supplied-file reader. Apache-2.0.

Assess supplied file bytes, not an HTTP observation. Stdlib only, no network.
Frozen expectations are separate; never generated by this reader.
"""
import base64
import binascii
import hashlib
import re
import zlib
from xml.parsers import expat

NS = 'http://www.sitemaps.org/schemas/sitemap/0.9'
RAW_LIMIT = 5_242_880
BYTE_LIMIT = 52_428_800
ENTRY_LIMIT = 50_000
NODE_LIMIT = 300_000
DEPTH_LIMIT = 16
LEAF_LIMIT = 4096
UNKNOWN = 'inconclusive'

class IntakeError(ValueError):
    """Technical intake refusal, never a control verdict."""

class _Stop(Exception):
    pass

class _Reading:
    def __init__(self):
        self.kind = None
        self.count = 0
        self.stack = []
        self.nodes = 0
        self.failures = []
        self.unknowns = []
        self.locations = []
        self.root_seen = False
        self.root_ended = False
        self.excess = False
        self.entry = None
        self.leaf = None
        self.leaf_text = ''

    def fail(self, reason):
        if reason not in self.failures:
            self.failures.append(reason)

    def unknown(self, reason):
        if reason not in self.unknowns:
            self.unknowns.append(reason)

    @staticmethod
    def split(name):
        return name.rsplit('|', 1) if '|' in name else ('', name)

    def start(self, name, attrs):
        self.nodes += 1
        if self.nodes > NODE_LIMIT or len(self.stack) >= DEPTH_LIMIT:
            self.unknown('reader-resource-bound')
            raise _Stop()
        uri, local = self.split(name)
        depth = len(self.stack)
        if depth == 0:
            self.root_seen = True
            if local not in ('urlset', 'sitemapindex'):
                self.unknown('root-outside-profile')
                raise _Stop()
            if uri != NS:
                self.fail('root-namespace-not-sitemaps-0.9')
                raise _Stop()
            self.kind = 'urlset' if local == 'urlset' else 'index'
            allowed = {'http://www.w3.org/2001/XMLSchema-instance|schemaLocation'}
            if set(attrs) - allowed:
                self.unknown('unqualified-root-attribute')
        else:
            if attrs:
                self.unknown('unqualified-attribute')
            expected_entry = 'url' if self.kind == 'urlset' else 'sitemap'
            if depth == 1:
                self.entry = None
                if uri == NS and local == expected_entry:
                    self.count += 1
                    if self.count > ENTRY_LIMIT:
                        self.excess = True
                        self.unknown('entry-limit-stopped-prefix')
                        raise _Stop()
                    self.entry = {'seen': [], 'loc': None}
                elif uri == NS:
                    self.fail('unexpected-base-entry')
                else:
                    self.unknown('unqualified-extension')
            elif depth == 2 and self.entry is not None:
                order = ['loc','lastmod','changefreq','priority'] if self.kind == 'urlset' else ['loc','lastmod']
                if uri != NS:
                    self.unknown('unqualified-extension')
                elif local not in order:
                    self.fail('unexpected-base-leaf')
                else:
                    seen = self.entry['seen']
                    if local in seen:
                        self.fail('duplicate-base-leaf')
                    if seen and order.index(local) < max(order.index(x) for x in seen):
                        self.fail('base-leaves-out-of-order')
                    seen.append(local)
                    self.leaf = local
                    self.leaf_text = ''
            elif depth >= 3 and self.leaf is not None:
                self.fail('nested-base-leaf')
        self.stack.append(name)

    def text(self, value):
        if self.leaf is not None:
            if len(self.leaf_text) + len(value) > LEAF_LIMIT:
                self.unknown('leaf-resource-bound')
                raise _Stop()
            self.leaf_text += value
        elif value.strip(' \t\r\n'):
            # Foreign extensions are outside this profile, not base errors.
            if all(self.split(x)[0] == NS for x in self.stack):
                self.fail('mixed-base-text')

    def end(self, name):
        depth = len(self.stack)
        if depth == 3 and self.leaf is not None:
            if self.leaf == 'loc':
                self.entry['loc'] = self.leaf_text.strip(' \t\r\n')
                if not self.entry['loc']:
                    self.fail('empty-loc')
            self.leaf = None
            self.leaf_text = ''
        if depth == 2 and self.entry is not None:
            if 'loc' not in self.entry['seen']:
                self.fail('missing-loc')
            elif self.entry['seen'][0] != 'loc':
                self.fail('loc-not-first')
            if self.entry['loc']:
                self.locations.append(self.entry['loc'])
            self.entry = None
        self.stack.pop()
        if depth == 1:
            self.root_ended = True
            if self.count == 0:
                self.fail('empty-sitemap')

    def doctype(self, *args):
        self.unknown('doctype-outside-profile')
        raise _Stop()


def _xml(data):
    reading = _Reading()
    parser = expat.ParserCreate('UTF-8', namespace_separator='|')
    parser.StartElementHandler = reading.start
    parser.EndElementHandler = reading.end
    parser.CharacterDataHandler = reading.text
    parser.StartDoctypeDeclHandler = reading.doctype
    parser.EntityDeclHandler = reading.doctype
    parser.ExternalEntityRefHandler = lambda *args: 0
    parser.SetParamEntityParsing(expat.XML_PARAM_ENTITY_PARSING_NEVER)
    complete = False
    try:
        for offset in range(0, len(data), 65536):
            parser.Parse(data[offset:offset+65536], False)
        parser.Parse(b'', True)
        complete = True
    except _Stop:
        pass
    except expat.ExpatError:
        reading.fail('malformed-xml')
    return reading, complete


def _attributed_root(data):
    """Read at most 64KiB to the first root, never its content or an entity.

    Expat's encoding detection is used only for attribution. It never makes a
    non-UTF8 document acceptable, and no decoded/repaired original is returned.
    """
    found = []
    parser = expat.ParserCreate(namespace_separator='|')
    def start(name, attrs):
        uri, local = _Reading.split(name)
        if uri == NS and local in ('urlset','sitemapindex'):
            found.append('urlset' if local == 'urlset' else 'index')
        raise _Stop()
    def stop(*args):
        raise _Stop()
    parser.StartElementHandler = start
    parser.StartDoctypeDeclHandler = stop
    parser.EntityDeclHandler = stop
    parser.ExternalEntityRefHandler = lambda *args: 0
    parser.SetParamEntityParsing(expat.XML_PARAM_ENTITY_PARSING_NEVER)
    try:
        parser.Parse(data[:65536], False)
    except (_Stop, expat.ExpatError):
        pass
    return found[0] if found else None


def _encoding_failure(data, reason):
    attributed = _attributed_root(data)
    return _result(fmt='fail' if attributed else UNKNOWN,
                   reasons=[reason] + ([] if attributed else ['sitemaps-root-not-attributed']),
                   decoded_bytes_read=len(data), byte_measurement='exact',
                   root_attribution=attributed)


def _result(fmt=UNKNOWN, limits=UNKNOWN, kind=None, count=None, reasons=(), **extra):
    return dict(format=fmt, limits=limits, kind=kind, count=count,
                reasons=list(reasons), locations=[], **extra)


def read_native(raw, encoding, complete):
    if not isinstance(raw, bytes) or len(raw) > RAW_LIMIT:
        raise IntakeError('native file exceeds 5242880 raw bytes or is not bytes')
    if type(complete) is not bool or encoding not in ('identity', 'gzip'):
        raise IntakeError('explicit boolean completeness and identity/gzip encoding required')
    data = raw
    if encoding == 'gzip':
        decoder = zlib.decompressobj(16 + zlib.MAX_WBITS)
        parts = []
        total = 0
        try:
            for offset in range(0, len(raw), 65536):
                chunk = decoder.decompress(raw[offset:offset+65536], BYTE_LIMIT+1-total)
                parts.append(chunk)
                total += len(chunk)
                if total > BYTE_LIMIT:
                    break
            data = b''.join(parts)
            if total <= BYTE_LIMIT and (not decoder.eof or decoder.unused_data or decoder.unconsumed_tail):
                return _result(reasons=['incomplete-or-multiple-gzip-stream'])
        except zlib.error:
            return _result(reasons=['gzip-integrity-unresolved'])
    if len(data) > BYTE_LIMIT:
        kind = _attributed_root(data)
        return _result(limits='fail' if kind else UNKNOWN, kind=kind,
                       reasons=['decompressed-byte-limit-exceeded'] + ([] if kind else ['sitemaps-prefix-not-attributed']),
                       decoded_bytes_read=len(data), byte_measurement='lower-bound')
    if not complete:
        return _result(reasons=['supplied-file-incomplete'], decoded_bytes_read=len(data), byte_measurement='exact-supplied-bytes')
    try:
        text = data.decode('utf-8-sig')
    except UnicodeDecodeError:
        return _encoding_failure(data, 'not-utf8')
    # XML 1.0 forbids these literal characters. UTF-16/32 without BOM can
    # otherwise survive UTF-8 decoding as ASCII+NUL and trigger Expat autodetection.
    if re.search(r'[\x00-\x08\x0b\x0c\x0e-\x1f]', text):
        return _encoding_failure(data, 'invalid-utf8-xml-character')
    declaration = re.match(r'^<\?xml\s[^?]*encoding\s*=\s*[\"\x27]([^\"\x27]+)[\"\x27]', text)
    if declaration and declaration.group(1).lower() not in ('utf-8', 'utf8'):
        return _encoding_failure(data, 'non-utf8-declaration')
    del text
    reading, parsed = _xml(data)
    fmt = 'fail' if reading.failures and reading.root_seen else UNKNOWN if reading.unknowns or not parsed else 'pass'
    limits = 'fail' if reading.excess else 'pass' if parsed and reading.kind is not None else UNKNOWN
    count = reading.count if parsed or reading.excess else None
    result = _result(fmt, limits, reading.kind, count, reading.failures + reading.unknowns,
                     decoded_bytes_read=len(data), byte_measurement='exact', xml_complete=parsed)
    result['locations'] = reading.locations
    return result


def original_bytes(record):
    """Verify original bytes before reading; transport errors raise, not C/NC."""
    if not isinstance(record, dict) or set(record) != {'raw_base64','sha256','encoding','complete'}:
        raise IntakeError('native record fields must match the closed profile')
    encoded = record['raw_base64']
    if not isinstance(encoded, str) or len(encoded) > 4*((RAW_LIMIT+2)//3):
        raise IntakeError('base64 envelope too large')
    try:
        raw = base64.b64decode(encoded, validate=True)
    except (ValueError, binascii.Error) as exc:
        raise IntakeError('invalid base64') from exc
    if base64.b64encode(raw).decode('ascii') != encoded:
        raise IntakeError('noncanonical base64')
    if not isinstance(record['sha256'], str) or hashlib.sha256(raw).hexdigest() != record['sha256']:
        raise IntakeError('native original hash mismatch')
    if type(record['complete']) is not bool or record['encoding'] not in ('identity','gzip'):
        raise IntakeError('explicit completeness and encoding required')
    if len(raw)>RAW_LIMIT:raise IntakeError('native file exceeds raw byte bound')
    return raw


def read_record(record):
    return read_native(original_bytes(record), record['encoding'], record['complete'])
